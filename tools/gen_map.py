def cell_of(lat, lon):
    col = int((lon - LON_MIN) / DLON)
    row = int((LAT_TOP - lat) / DLAT)
    return row, col


def point_in_poly(lon, lat, poly):
    inside = False
    n = len(poly)
    j = n - 1
    for i in range(n):
        xi, yi = poly[i]
        xj, yj = poly[j]
        if (yi > lat) != (yj > lat):
            x_at = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < x_at:
                inside = not inside
        j = i
    return inside


def rasterize():
    grid = [[SEA] * W for _ in range(H)]
    for r in range(H):
        lat = LAT_TOP - (r + 0.5) * DLAT
        for c in range(W):
            lon = LON_MIN + (c + 0.5) * DLON
            land = any(point_in_poly(lon, lat, p) for p in LAND_POLYGONS)
            if land and any(point_in_poly(lon, lat, p) for p in LAKE_POLYGONS):
                land = False
            if land:
                grid[r][c] = LAND
    # 海岸線: 海に接する陸セルに輪郭文字を置く
    out = [row[:] for row in grid]
    for r in range(H):
        for c in range(W):
            if grid[r][c] != LAND:
                continue
            # グリッド外は海として扱い、クリップ端でも輪郭を閉じる
            n = r == 0 or grid[r - 1][c] == SEA
            s = r == H - 1 or grid[r + 1][c] == SEA
            w = c == 0 or grid[r][c - 1] == SEA
            e = c == W - 1 or grid[r][c + 1] == SEA
            if s:
                out[r][c] = '_'
            elif n:
                out[r][c] = '-'
            elif w or e:
                out[r][c] = '|'
    return out


def place_tags(grid):
    spans = {}
    for sid, (lat, lon, drow, dcol) in sorted(TAGS.items()):
        row, col = cell_of(lat, lon)
        row += drow
        col += dcol - 2          # タグ中央を座標に合わせる
        col = max(0, min(W - 5, col))
        row = max(0, min(H - 1, row))
        for other, (orow, ocol) in spans.items():
            if orow == row and not (col + 5 <= ocol or ocol + 5 <= col):
                raise SystemExit(
                    f'タグ衝突: {sid}({row},{col}) と {other}({orow},{ocol})')
        spans[sid] = (row, col)
        text = '{' + sid + '}'
        for i, ch in enumerate(text):
            grid[row][col + i] = ch
    return grid


def main():
    grid = place_tags(rasterize())
    lines = [''.join(row) for row in grid]
    if '--preview' in sys.argv:
        for line in lines:
            print(line)
        return
    out = os.path.join(os.path.dirname(__file__), '..', 'data', 'map_ascii.vim')
    with open(out, 'w') as f:
        f.write('scriptencoding utf-8\n')
        f.write('" 自動生成ファイル: tools/gen_map.py が出力する。手で編集しない。\n')
        f.write(f'" グリッド {W}x{H}、経度 {LON_MIN}..{LON_MAX}、'
                f'緯度 {LAT_BOT}..{LAT_TOP}\n')
        f.write('let g:vimtoria_data_map.template = [\n')
        for line in lines:
            f.write("      \\ '" + line + "',\n")
        f.write('      \\ ]\n')
    print(f'wrote {os.path.normpath(out)} ({W}x{H}, {len(TAGS)} tags)')


if __name__ == '__main__':
    main()
